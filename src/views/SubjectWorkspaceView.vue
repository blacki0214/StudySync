<script setup>
/**
 * SubjectWorkspaceView — the NotebookLM-style workspace for one subject:
 *   • Left   : add sources + the source list (toggle which feed the study set)
 *   • Center : AI-generated study material (summary / flashcards / quiz / keywords)
 *   • Right  : "Ask your sources"
 *
 * Generation runs through aiService, so it's real Gemini output when configured
 * (and falls back to the rule-based engine otherwise). It auto-runs when the
 * subject opens with sources, and re-runs (debounced) whenever the selected
 * sources change — so creating a subject and adding sources fills the study set
 * automatically. Flashcards can be saved into the Flashcards feature as a deck.
 */
import { ref, computed, onMounted, watch, reactive } from 'vue'
import { useI18n } from 'vue-i18n'
import { useSubjectStore } from '../stores/subjectStore.js'
import { useDocumentStore } from '../stores/documentStore.js'
import { useContentStore } from '../stores/contentStore.js'
import { useDialogStore } from '../stores/dialogStore.js'
import { isAiConfigured, summarize, generateFlashcards, generateQuiz, extractKeywords } from '../services/aiService.js'
import { cleanText } from '../utils/textAnalyzer.js'
import { exportStudyMarkdown, exportFlashcardsCsv, exportFlashcardsAnki } from '../utils/exporters.js'
import DocumentUploader from '../components/documents/DocumentUploader.vue'
import DocumentList from '../components/documents/DocumentList.vue'
import AskSourcesPanel from '../components/documents/AskSourcesPanel.vue'
import QuizGenerator from '../components/ai/QuizGenerator.vue'
import LoadingSpinner from '../components/common/LoadingSpinner.vue'
import TaskManager from '../components/tasks/TaskManager.vue'

const props = defineProps({ id: { type: String, required: true } })
const { t } = useI18n()
const subjectStore = useSubjectStore()
const documentStore = useDocumentStore()
const content = useContentStore()
const dialog = useDialogStore()

const ready = ref(false)
const busy = ref(false)
const section = ref('study') // 'study' | 'tasks'
const tab = ref('summary')
const selected = ref([]) // selected document ids
const showExport = ref(false)

const subject = computed(() => subjectStore.getById(props.id))
const docs = computed(() => documentStore.forSubject(props.id))
const selectedDocs = computed(() => docs.value.filter((d) => selected.value.includes(d.id)))
const corpus = computed(() => selectedDocs.value.map((d) => cleanText(d.extracted_text || '')).join('\n\n').trim())
const hasMaterial = computed(() => corpus.value.length > 0)

// --- AI-generated study material ------------------------------------------
const summary = ref([])
const flashcards = ref([])
const keywords = ref([])
const revealed = ref(new Set())
const gen = reactive({ summary: false, flashcards: false, keywords: false })
const saving = ref(false)
let genTimer = null

// Remember which corpus each section was generated for, so we DON'T fire all
// tabs at once (that bursts past Gemini's rate limit → 502s). We generate only
// the tab the user is viewing, once per corpus.
const genKey = { summary: '', flashcards: '', keywords: '' }
const sig = (c) => `${c.length}:${c.slice(0, 40)}`

async function genSummary() {
  if (!corpus.value || !isAiConfigured) { summary.value = []; return }
  genKey.summary = sig(corpus.value)
  gen.summary = true
  try { summary.value = await summarize(corpus.value, { max: 6 }) }
  catch { summary.value = []; genKey.summary = '' }
  finally { gen.summary = false }
}
async function genFlash() {
  if (!corpus.value || !isAiConfigured) { flashcards.value = []; return }
  genKey.flashcards = sig(corpus.value)
  gen.flashcards = true
  try {
    flashcards.value = await generateFlashcards(corpus.value, { max: 12 })
    revealed.value = new Set()
  } catch { flashcards.value = []; genKey.flashcards = '' }
  finally { gen.flashcards = false }
}
async function genKeywords() {
  if (!corpus.value || !isAiConfigured) { keywords.value = []; return }
  genKey.keywords = sig(corpus.value)
  gen.keywords = true
  try { keywords.value = await extractKeywords(corpus.value, { limit: 14 }) }
  catch { keywords.value = []; genKey.keywords = '' }
  finally { gen.keywords = false }
}

// Generate ONLY the active tab, and only if it isn't already done for this
// corpus. (Quiz is generated by its own child component when its tab is open.)
function ensureActiveTab() {
  if (!hasMaterial.value || !isAiConfigured) return
  const s = sig(corpus.value)
  if (tab.value === 'summary' && genKey.summary !== s) genSummary()
  else if (tab.value === 'flashcards' && genKey.flashcards !== s) genFlash()
  else if (tab.value === 'keywords' && genKey.keywords !== s) genKeywords()
}

function toggleReveal(i) {
  const set = new Set(revealed.value)
  set.has(i) ? set.delete(i) : set.add(i)
  revealed.value = set
}

// Save the generated flashcards into the Flashcards feature as a studyable deck.
async function saveDeck() {
  if (!flashcards.value.length) { dialog.toast(t('workspace.noCards'), 'warning'); return }
  const name = await dialog.promptText({
    title: t('workspace.saveDeck'),
    label: t('flashcards.deckName'),
    value: subject.value?.name || t('flashcards.newDeck')
  })
  if (!name || !name.trim()) return
  saving.value = true
  try {
    const deck = await content.createDeck({
      name: name.trim(),
      subjectCode: subject.value?.code || '',
      color: subject.value?.color || 'grad-blue',
      cards: flashcards.value.map((c) => ({ question: c.question, answer: c.answer }))
    })
    dialog.toast(t('workspace.deckSaved', { n: deck.cards.length }), 'success')
  } catch {
    dialog.toast(t('workspace.deckSaveFailed'), 'error')
  } finally {
    saving.value = false
  }
}

onMounted(async () => {
  if (!subjectStore.subjects.length) await subjectStore.fetchSubjects()
  await documentStore.fetchForSubject(props.id)
  selected.value = docs.value.map((d) => d.id) // study everything by default
  ready.value = true
  ensureActiveTab() // generate just the default (summary) tab on open
})

// Generate a tab's material the first time the user opens it.
watch(tab, ensureActiveTab)

// Keep selection valid as documents are added/removed.
watch(docs, (list) => {
  const ids = new Set(list.map((d) => d.id))
  selected.value = selected.value.filter((id) => ids.has(id))
})

// When the studied corpus changes, invalidate caches and (debounced) regenerate
// ONLY the active tab — not all of them.
watch(corpus, () => {
  clearTimeout(genTimer)
  genKey.summary = genKey.flashcards = genKey.keywords = ''
  summary.value = []; flashcards.value = []; keywords.value = []
  if (!hasMaterial.value) return
  genTimer = setTimeout(ensureActiveTab, 500)
})

function toggle(id) {
  selected.value = selected.value.includes(id)
    ? selected.value.filter((x) => x !== id)
    : [...selected.value, id]
}

async function add(payload) {
  busy.value = true
  try {
    const row = await documentStore.addDocument({ subjectId: props.id, ...payload })
    selected.value = [...selected.value, row.id]
  } finally {
    busy.value = false
  }
}

async function remove(doc) {
  await documentStore.removeDocument(props.id, doc)
}

async function doExport(kind) {
  showExport.value = false
  const name = subject.value?.name || 'StudySync'
  // Reuse the already-generated AI study material; fetch a quiz on demand for MD.
  if (kind === 'csv') { exportFlashcardsCsv(flashcards.value, name); return }
  if (kind === 'anki') { exportFlashcardsAnki(flashcards.value, name); return }
  if (kind === 'md') {
    let quiz = []
    try { quiz = await generateQuiz(corpus.value, { max: 8 }) } catch { /* export without quiz */ }
    exportStudyMarkdown({ name, summary: summary.value, flashcards: flashcards.value, quiz })
  }
}
</script>

<template>
  <LoadingSpinner v-if="!ready" :label="t('workspace.loading')" />

  <div v-else-if="!subject" class="empty-state">
    <i class="bi bi-folder-x empty-icon"></i>
    <p>{{ t('workspace.notFound') }}</p>
    <router-link to="/my-subjects" class="btn btn-brand">{{ t('mySubjects.title') }}</router-link>
  </div>

  <div v-else class="workspace">
    <!-- Header -->
    <header class="page-head">
      <div class="ws-head">
        <span class="icon-tile ws-badge" :class="subject.color">{{ subject.letters }}</span>
        <div>
          <h1 class="ph-title">{{ subject.name }}</h1>
          <p class="ph-sub">{{ t('workspace.sub', { n: docs.length }) }}</p>
        </div>
      </div>
      <div class="action-row">
        <div class="dropdown">
          <button class="btn btn-outline-soft" :disabled="!hasMaterial" data-bs-toggle="dropdown">
            <i class="bi bi-download"></i>{{ t('workspace.export') }}
          </button>
          <ul class="dropdown-menu dropdown-menu-end">
            <li><button class="dropdown-item" @click="doExport('md')"><i class="bi bi-markdown"></i>{{ t('workspace.exportMd') }}</button></li>
            <li><button class="dropdown-item" @click="doExport('csv')"><i class="bi bi-filetype-csv"></i>{{ t('workspace.exportCsv') }}</button></li>
            <li><button class="dropdown-item" @click="doExport('anki')"><i class="bi bi-card-text"></i>{{ t('workspace.exportAnki') }}</button></li>
          </ul>
        </div>
      </div>
    </header>

    <!-- Section switch: study workspace vs. task tracker -->
    <div class="ws-section-switch">
      <button class="tvs-btn" :class="{ active: section==='study' }" @click="section='study'">
        <i class="bi bi-journal-text"></i>{{ t('workspace.sectionStudy') }}
      </button>
      <button class="tvs-btn" :class="{ active: section==='tasks' }" @click="section='tasks'">
        <i class="bi bi-check2-square"></i>{{ t('workspace.sectionTasks') }}
      </button>
    </div>

    <TaskManager v-if="section==='tasks'" :subject-id="props.id" />

    <div v-else class="workspace-grid">
      <!-- Left: sources -->
      <aside class="ws-col ws-sources">
        <DocumentUploader :busy="busy" @add="add" />
        <DocumentList :docs="docs" :selected="selected" @toggle="toggle" @remove="remove" />
      </aside>

      <!-- Center: study material -->
      <section class="ws-col ws-material">
        <div v-if="!hasMaterial" class="panel empty-state">
          <i class="bi bi-stars empty-icon"></i>
          <p>{{ t('workspace.materialEmpty') }}</p>
        </div>
        <div v-else-if="!isAiConfigured" class="panel empty-state">
          <i class="bi bi-stars empty-icon"></i>
          <p>{{ t('ai.disabled') }}</p>
        </div>
        <template v-else>
          <div class="text-tabs">
            <button class="text-tab" :class="{ active: tab==='summary' }" @click="tab='summary'">{{ t('workspace.tabSummary') }}</button>
            <button class="text-tab" :class="{ active: tab==='flashcards' }" @click="tab='flashcards'">{{ t('workspace.tabFlashcards') }}</button>
            <button class="text-tab" :class="{ active: tab==='quiz' }" @click="tab='quiz'">{{ t('workspace.tabQuiz') }}</button>
            <button class="text-tab" :class="{ active: tab==='keywords' }" @click="tab='keywords'">{{ t('workspace.tabKeywords') }}</button>
          </div>

          <!-- Summary -->
          <div v-if="tab==='summary'" class="panel ws-panel">
            <div class="ws-panel-head">
              <div class="section-title mb-0"><i class="bi bi-card-list"></i>{{ t('workspace.tabSummary') }}
                <span v-if="isAiConfigured" class="badge-soft ws-ai"><i class="bi bi-stars"></i> AI</span>
              </div>
              <button class="btn btn-soft btn-sm" :disabled="gen.summary" @click="genSummary">
                <i class="bi" :class="gen.summary ? 'bi-arrow-repeat spin' : 'bi-arrow-clockwise'"></i>{{ t('workspace.regenerate') }}
              </button>
            </div>
            <div v-if="gen.summary && !summary.length" class="ws-loading"><i class="bi bi-arrow-repeat spin"></i> {{ t('workspace.generating') }}</div>
            <p v-else-if="!summary.length" class="tool-empty">{{ t('workspace.summaryEmpty') }}</p>
            <ol v-else class="ws-summary">
              <li v-for="(s, i) in summary" :key="i"><span class="ws-sum-num">{{ i + 1 }}</span><span>{{ s }}</span></li>
            </ol>
          </div>

          <!-- Flashcards -->
          <div v-else-if="tab==='flashcards'" class="panel ws-panel">
            <div class="ws-panel-head">
              <div class="section-title mb-0"><i class="bi bi-card-text"></i>{{ t('workspace.tabFlashcards') }}
                <span class="badge-soft">{{ flashcards.length }}</span>
                <span v-if="isAiConfigured" class="badge-soft ws-ai"><i class="bi bi-stars"></i> AI</span>
              </div>
              <div class="ws-head-actions">
                <button class="btn btn-soft btn-sm" :disabled="gen.flashcards" @click="genFlash">
                  <i class="bi" :class="gen.flashcards ? 'bi-arrow-repeat spin' : 'bi-arrow-clockwise'"></i>{{ t('workspace.regenerate') }}
                </button>
                <button class="btn btn-brand btn-sm" :disabled="saving || !flashcards.length" @click="saveDeck">
                  <i class="bi" :class="saving ? 'bi-arrow-repeat spin' : 'bi-folder-plus'"></i>{{ t('workspace.saveDeck') }}
                </button>
              </div>
            </div>
            <div v-if="gen.flashcards && !flashcards.length" class="ws-loading"><i class="bi bi-arrow-repeat spin"></i> {{ t('workspace.generating') }}</div>
            <p v-else-if="!flashcards.length" class="tool-empty">{{ t('workspace.flashEmpty') }}</p>
            <div v-else class="ws-fc-grid">
              <button v-for="(c, i) in flashcards" :key="i" class="ws-fc" :class="{ revealed: revealed.has(i) }" @click="toggleReveal(i)">
                <div class="ws-fc-q">{{ c.question }}</div>
                <div class="ws-fc-a" :class="{ hint: !revealed.has(i) }">{{ revealed.has(i) ? c.answer : t('workspace.clickReveal') }}</div>
              </button>
            </div>
          </div>

          <!-- Quiz (interactive, AI-backed) -->
          <div v-else-if="tab==='quiz'" class="panel ws-panel">
            <QuizGenerator :content="corpus" />
          </div>

          <!-- Keywords -->
          <div v-else class="panel ws-panel">
            <div class="ws-panel-head">
              <div class="section-title mb-0"><i class="bi bi-tags"></i>{{ t('keywords.title') }}
                <span v-if="isAiConfigured" class="badge-soft ws-ai"><i class="bi bi-stars"></i> AI</span>
              </div>
              <button class="btn btn-soft btn-sm" :disabled="gen.keywords" @click="genKeywords">
                <i class="bi" :class="gen.keywords ? 'bi-arrow-repeat spin' : 'bi-arrow-clockwise'"></i>{{ t('workspace.regenerate') }}
              </button>
            </div>
            <div v-if="gen.keywords && !keywords.length" class="ws-loading"><i class="bi bi-arrow-repeat spin"></i> {{ t('workspace.generating') }}</div>
            <p v-else-if="!keywords.length" class="tool-empty">{{ t('keywords.empty') }}</p>
            <div v-else class="keyword-cloud">
              <span
                v-for="k in keywords"
                :key="k.word"
                class="keyword-tag"
                :class="{ 'is-technical': k.technical }"
              >{{ k.word }}<span class="kw-count">{{ k.count }}</span></span>
            </div>
          </div>
        </template>
      </section>

      <!-- Right: ask -->
      <aside class="ws-col ws-ask">
        <AskSourcesPanel :docs="selectedDocs" />
      </aside>
    </div>
  </div>
</template>
